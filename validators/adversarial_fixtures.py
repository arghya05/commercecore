"""Independently-authored adversarial fixtures. Per EXECUTION_PLAN.md §3 (R2, P0).

These fixtures are written separately from the main generation pipeline,
specifically to demonstrate that mechanical_validator.py's checks (schema
validity, source-span binding, execution correctness) do NOT establish
semantic fidelity (property 4). Each fixture has:
  - input: the source text and a generated (possibly wrong) contract.
  - naive_validator_verdict: what mechanical_validator.py actually says.
  - correct_answer: what a semantically-aware check must conclude.

A fixture set generated by the same pipeline it's meant to stress-test would
not serve this purpose -- these are hand-written, not sampled from the
synthetic generation pipeline being validated.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Callable, Dict, List, Optional

from validators.mechanical_validator import (
    ValidationResult,
    check_source_span_binding,
)
from schemas.common import EvidenceSpan


@dataclass
class AdversarialFixture:
    fixture_id: str
    category: str  # negation | omitted_constraint | units_mismatch | conflicting_facts | missing_field
    description: str
    source_text: str
    generated_spans: List[EvidenceSpan]
    naive_check_passes: bool  # what a naive substring/schema check says
    is_actually_correct: bool  # ground truth, established by the fixture author, not by any automated check
    notes: str


def _fixture_negation() -> AdversarialFixture:
    """The exact false-positive example from EXECUTION_PLAN.md §3: citing the
    substring "cotton" as evidence for a "material is cotton" claim, when the
    source text actually says the product does NOT contain cotton."""
    source = "This jacket contains no cotton; shell is 100% recycled polyester."
    span_text = "cotton"
    start = source.index(span_text)
    span = EvidenceSpan(start=start, end=start + len(span_text), text=span_text)
    return AdversarialFixture(
        fixture_id="negation-001",
        category="negation",
        description=(
            "Generated contract claims material=cotton, citing the substring "
            "'cotton' from source text 'contains no cotton'. Substring is "
            "present and correctly bound (naive check passes) but the claim "
            "is the exact opposite of what the source states."
        ),
        source_text=source,
        generated_spans=[span],
        naive_check_passes=True,
        is_actually_correct=False,
        notes="Span-binding alone cannot detect negation scope. Requires an explicit negation-aware check.",
    )


def _fixture_omitted_constraint() -> AdversarialFixture:
    """The exact under-specification example from EXECUTION_PLAN.md §3:
    'nuts without added sugar' -- a generated contract could keep only the
    nuts constraint and silently drop the sugar constraint. The simulator
    can execute the (incomplete) contract just fine."""
    source = "unsweetened oat drink 1 litre without peanuts, no added sugar"
    span_text = "without peanuts"
    start = source.index(span_text)
    span = EvidenceSpan(start=start, end=start + len(span_text), text=span_text)
    return AdversarialFixture(
        fixture_id="omitted-constraint-001",
        category="omitted_constraint",
        description=(
            "Source has THREE explicit requirements (unsweetened/no added "
            "sugar, 1 litre, no peanuts). A generated contract that only "
            "captures the peanut constraint is schema-valid and its one "
            "cited span is correctly bound, but it silently dropped two "
            "critical requirements."
        ),
        source_text=source,
        generated_spans=[span],  # only 1 of 3 required constraints represented
        naive_check_passes=True,
        is_actually_correct=False,
        notes="Neither schema validity nor span-binding can detect an ABSENT constraint -- there's nothing to check against, since the model never emitted it. Requires a completeness check against a pre-specified structured scenario (§3's 'structured-scenario-first' pipeline requirement).",
    )


