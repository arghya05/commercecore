def _fixture_missing_field_not_negative() -> AdversarialFixture:
    """The inverse failure mode: a validator that's too strict. Absence of
    evidence must map to `unknown`, not `fail` -- plans/00_shared_core.md:
    'a missing field is not a negative factual label'."""
    source = "Wireless mouse, 2.4GHz, USB receiver included."
    return AdversarialFixture(
        fixture_id="missing-field-001",
        category="missing_field",
        description=(
            "Query requires 'Bluetooth compatible'. Source text says nothing "
            "about Bluetooth at all (it describes a 2.4GHz USB-receiver "
            "mouse, which is a different, non-Bluetooth technology). The "
            "CORRECT contract state for the Bluetooth requirement is "
            "'unknown' (no evidence either way) -- NOT 'fail' (which would "
            "require an explicit contradiction) and NOT 'pass' (no positive "
            "evidence exists)."
        ),
        source_text=source,
        generated_spans=[],  # no evidence to cite -- that's the point
        naive_check_passes=True,  # trivially "passes" schema validity with zero spans
        is_actually_correct=True,  # IS correct IF the contract states 'unknown', wrong if it states 'fail' or 'pass'
        notes="This fixture is about the correct handling of absence-of-evidence, not a false positive like the others. A validator must not conflate 'no evidence found' with either 'confirmed false' or 'confirmed true'.",
    )


ALL_FIXTURES: List[AdversarialFixture] = [
    _fixture_negation(),
    _fixture_omitted_constraint(),
    _fixture_units_mismatch(),
    _fixture_conflicting_facts(),
    _fixture_missing_field_not_negative(),
]


def run_naive_check(fixture: AdversarialFixture) -> bool:
    """Runs ONLY the mechanical span-binding check (property 2) against a
    fixture and reports whether it passes -- this is what a naive validator
    relying solely on substring-presence would conclude."""
    if not fixture.generated_spans:
        return True  # vacuously "passes" -- nothing to check
    all_bound, _ = check_source_span_binding(fixture.generated_spans, fixture.source_text)
    return all_bound


def report() -> None:
    """Run every fixture through the naive check and report whether the
    naive check's verdict matches ground truth -- this demonstrates,
    concretely and honestly, which failure modes the current mechanical
    validator catches and which it does not."""
    print(f"{'fixture_id':<28} {'category':<22} {'naive_says_ok':<15} {'ground_truth_ok':<17} {'gap?'}")
    print("-" * 100)
    n_gaps = 0
    for fx in ALL_FIXTURES:
        naive_result = run_naive_check(fx)
        expected_naive = fx.naive_check_passes
        assert naive_result == expected_naive, (
            f"Fixture {fx.fixture_id}: expected naive check to say "
            f"{expected_naive}, but mechanical_validator actually said {naive_result}. "
            f"Fixture authoring bug -- fix the fixture's generated_spans/naive_check_passes."
        )
        gap = (naive_result != fx.is_actually_correct)
        if gap:
            n_gaps += 1
        print(
            f"{fx.fixture_id:<28} {fx.category:<22} {str(naive_result):<15} "
            f"{str(fx.is_actually_correct):<17} {'YES -- naive check insufficient' if gap else 'no gap'}"
        )
    print("-" * 100)
    print(
        f"{n_gaps}/{len(ALL_FIXTURES)} fixtures demonstrate a real gap between the naive "
        f"mechanical check and semantic ground truth. This is EXPECTED and is the "
        f"entire point of §3's four-property distinction -- these gaps are why "
        f"property 4 (semantic fidelity) cannot be certified by mechanical_validator.py "
        f"alone, and why grocery/synthetic data must be reported as synthetic-scenario "
        f"performance rather than assumed semantically correct."
    )


if __name__ == "__main__":
    report()
    print("\nALL validators/adversarial_fixtures.py SMOKE CHECKS PASSED "
          "(fixtures are internally consistent; the naive-vs-ground-truth gap is demonstrated, not hidden)")
